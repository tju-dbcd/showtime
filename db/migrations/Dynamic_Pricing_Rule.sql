-- Create DYNAMIC_PRICING_RULE Table
CREATE TABLE DYNAMIC_PRICING_RULE (
    RULE_ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SESSION_ID NUMBER(19,0) NOT NULL,
    SEAT_SECTION_ID NUMBER(19,0),
    RULE_NAME VARCHAR2(100) NOT NULL,
    TRIGGER_TYPE VARCHAR2(30) NOT NULL,
    ADJUSTMENT_TYPE VARCHAR2(20) NOT NULL,
    ADJUSTMENT_VALUE NUMBER(10,2) NOT NULL,
    PRIORITY NUMBER(10,0) DEFAULT 0 NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'ENABLED' NOT NULL,
    CREATE_BY VARCHAR2(64) DEFAULT 'SYSTEM' NOT NULL,
    CREATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATE_BY VARCHAR2(64) DEFAULT 'SYSTEM' NOT NULL,
    UPDATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_DPR_SESSION FOREIGN KEY (SESSION_ID) REFERENCES SHOW_SESSION(SESSION_ID) ON DELETE CASCADE,
    CONSTRAINT FK_DPR_SECTION FOREIGN KEY (SEAT_SECTION_ID) REFERENCES SEAT_SECTION(SEAT_SECTION_ID) ON DELETE SET NULL
);

CREATE INDEX IX_DPR_SESSION_ID ON DYNAMIC_PRICING_RULE(SESSION_ID);
CREATE INDEX IX_DPR_SECTION_ID ON DYNAMIC_PRICING_RULE(SEAT_SECTION_ID);
