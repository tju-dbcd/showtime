CREATE TABLE DYNAMIC_PRICING_RULE (
    RULE_ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SESSION_ID NUMBER(19,0) NOT NULL,
    SEAT_SECTION_ID NUMBER(19,0),
    RULE_NAME VARCHAR2(100 CHAR) NOT NULL,
    TRIGGER_TYPE VARCHAR2(30 CHAR) NOT NULL,
    START_OFFSET_MINUTES NUMBER(10,0),
    END_OFFSET_MINUTES NUMBER(10,0),
    ADJUSTMENT_TYPE VARCHAR2(20 CHAR) NOT NULL,
    ADJUSTMENT_VALUE NUMBER(10,2) NOT NULL,
    PRIORITY NUMBER(5,0) DEFAULT 0 NOT NULL,
    STATUS VARCHAR2(20 CHAR) DEFAULT 'ENABLED' NOT NULL,
    CREATE_BY VARCHAR2(50 CHAR),
    CREATE_TIME TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATE_BY VARCHAR2(50 CHAR),
    UPDATE_TIME TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_DPR_SESSION FOREIGN KEY (SESSION_ID) REFERENCES SHOW_SESSION(SESSION_ID) ON DELETE CASCADE,
    CONSTRAINT FK_DPR_SECTION FOREIGN KEY (SEAT_SECTION_ID) REFERENCES SEAT_SECTION(SEAT_SECTION_ID) ON DELETE SET NULL,
    CONSTRAINT CK_DPR_TRIGGER_TYPE CHECK (TRIGGER_TYPE IN ('TIME_WINDOW', 'INVENTORY_RATE')),
    CONSTRAINT CK_DPR_ADJUSTMENT_TYPE CHECK (ADJUSTMENT_TYPE IN ('DISCOUNT_RATE', 'AMOUNT_OFF', 'FIXED_PRICE')),
    CONSTRAINT CK_DPR_STATUS CHECK (STATUS IN ('ENABLED', 'DISABLED'))
);

CREATE INDEX IDX_DPR_SESSION ON DYNAMIC_PRICING_RULE(SESSION_ID);
CREATE INDEX IDX_DPR_SECTION ON DYNAMIC_PRICING_RULE(SEAT_SECTION_ID);
