-- 1. 座位主图表
CREATE TABLE SEAT_MAP (
    SEAT_MAP_ID     NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    VENUE_ID        NUMBER(19) NOT NULL,
    MAP_CODE        VARCHAR2(50 CHAR) NOT NULL,
    MAP_NAME        VARCHAR2(100 CHAR) NOT NULL,
    MAP_VERSION     VARCHAR2(20 CHAR) DEFAULT 'V1' NOT NULL,
    IS_DEFAULT      CHAR(1) DEFAULT 'N' NOT NULL,
    MAP_WIDTH       NUMBER(10,2),
    MAP_HEIGHT      NUMBER(10,2),
    MAP_STATUS      VARCHAR2(20 CHAR) DEFAULT 'DRAFT' NOT NULL,
    REMARK          VARCHAR2(255 CHAR),
    CREATE_TIME     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATE_TIME     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CREATE_BY       VARCHAR2(50 CHAR),
    UPDATE_BY       VARCHAR2(50 CHAR),

    CONSTRAINT PK_SEAT_MAP PRIMARY KEY (SEAT_MAP_ID),
    CONSTRAINT UK_SEAT_MAP_VENUE_CODE UNIQUE (VENUE_ID, MAP_CODE),
    --CONSTRAINT FK_SEAT_MAP_VENUE FOREIGN KEY (VENUE_ID) REFERENCES VENUE(VENUE_ID),
    CONSTRAINT CK_SEAT_MAP_DEFAULT CHECK (IS_DEFAULT IN ('Y', 'N')),
    CONSTRAINT CK_SEAT_MAP_STATUS CHECK (MAP_STATUS IN ('DRAFT', 'ENABLED', 'DISABLED')),
    CONSTRAINT CK_SEAT_MAP_SIZE CHECK ( (MAP_WIDTH IS NULL OR MAP_WIDTH > 0) AND (MAP_HEIGHT IS NULL OR MAP_HEIGHT > 0))
);

-- 同一场馆只能有一张默认座位图

CREATE UNIQUE INDEX UK_SEAT_MAP_DEFAULT ON SEAT_MAP(VENUE_ID, CASE WHEN IS_DEFAULT='Y' THEN 1 END);



-- 2. 座位分区表
CREATE TABLE SEAT_SECTION (
    SEAT_SECTION_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    SEAT_MAP_ID     NUMBER(19) NOT NULL,
    SECTION_CODE    VARCHAR2(30 CHAR) NOT NULL,
    SECTION_NAME    VARCHAR2(100 CHAR) NOT NULL,
    SECTION_TYPE    VARCHAR2(20 CHAR) DEFAULT 'NORMAL' NOT NULL,
    SECTION_COLOR   VARCHAR2(20 CHAR),
    FLOOR_NO        VARCHAR2(20 CHAR),
    IS_SELLABLE     CHAR(1) DEFAULT 'Y' NOT NULL,
    DISPLAY_ORDER   NUMBER(5) DEFAULT 0 NOT NULL,
    REMARK          VARCHAR2(255 CHAR),
    CREATE_TIME     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATE_TIME     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CREATE_BY       VARCHAR2(50 CHAR),
    UPDATE_BY       VARCHAR2(50 CHAR),

    CONSTRAINT PK_SEAT_SECTION PRIMARY KEY (SEAT_SECTION_ID),
    CONSTRAINT FK_SEAT_SECTION_MAP FOREIGN KEY (SEAT_MAP_ID)REFERENCES SEAT_MAP(SEAT_MAP_ID),
    CONSTRAINT UK_SEAT_SECTION_MAP_CODE UNIQUE (SEAT_MAP_ID, SECTION_CODE),
    CONSTRAINT CK_SEAT_SECTION_TYPE CHECK (SECTION_TYPE IN ('NORMAL', 'VIP', 'ACCESSIBLE', 'STANDING')),
    CONSTRAINT CK_SEAT_SECTION_SELLABLE CHECK (IS_SELLABLE IN ('Y', 'N')),
    CONSTRAINT CK_SEAT_SECTION_DISPLAY_ORDER CHECK (DISPLAY_ORDER >= 0)
);


-- 3. 具体座位表
CREATE TABLE SEAT (
    SEAT_ID          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    SEAT_SECTION_ID NUMBER(19) NOT NULL,
    ROW_CODE         VARCHAR2(20 CHAR) NOT NULL,
    SEAT_NO          VARCHAR2(20 CHAR) NOT NULL,
    ROW_INDEX        NUMBER(5) NOT NULL,
    COL_INDEX        NUMBER(5) NOT NULL,
    X_COORD          NUMBER(10,2) DEFAULT 0 NOT NULL,
    Y_COORD          NUMBER(10,2) DEFAULT 0 NOT NULL,
    SEAT_TYPE        VARCHAR2(20 CHAR) DEFAULT 'NORMAL' NOT NULL,
    SEAT_STATUS      VARCHAR2(20 CHAR) DEFAULT 'ENABLED' NOT NULL,
    IS_AISLE_SIDE    CHAR(1) DEFAULT 'N' NOT NULL,
    IS_SELLABLE      CHAR(1) DEFAULT 'Y' NOT NULL,
    REMARK           VARCHAR2(255 CHAR),
    CREATE_TIME      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATE_TIME      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CREATE_BY        VARCHAR2(50 CHAR),
    UPDATE_BY        VARCHAR2(50 CHAR),

    CONSTRAINT PK_SEAT PRIMARY KEY (SEAT_ID),
    CONSTRAINT FK_SEAT_SECTION FOREIGN KEY (SEAT_SECTION_ID) REFERENCES SEAT_SECTION(SEAT_SECTION_ID),
    CONSTRAINT UK_SEAT_ROW_NO UNIQUE (SEAT_SECTION_ID, ROW_CODE, SEAT_NO),
    CONSTRAINT UK_SEAT_POSITION UNIQUE (SEAT_SECTION_ID, ROW_INDEX, COL_INDEX),
    CONSTRAINT CK_SEAT_TYPE CHECK (SEAT_TYPE IN ('NORMAL', 'COUPLE', 'ACCESSIBLE', 'COMPANION') ),
    CONSTRAINT CK_SEAT_STATUS CHECK (SEAT_STATUS IN ('ENABLED', 'DISABLED', 'MAINTENANCE')),
    CONSTRAINT CK_SEAT_AISLE_SIDE CHECK (IS_AISLE_SIDE IN ('Y', 'N')),
    CONSTRAINT CK_SEAT_SELLABLE CHECK (IS_SELLABLE IN ('Y', 'N')),
    CONSTRAINT CK_SEAT_INDEX CHECK (ROW_INDEX >= 0 AND COL_INDEX >= 0)
);


-- 4. 座位锁表
CREATE TABLE SEAT_LOCK (
    SEAT_LOCK_ID    NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    SESSION_ID      NUMBER(19) NOT NULL,
    SEAT_ID         NUMBER(19) NOT NULL,
    USER_ID         NUMBER(19) NOT NULL,
    LOCK_TOKEN      VARCHAR2(64 CHAR) NOT NULL,
    LOCK_STATUS     VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    LOCK_TIME       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    EXPIRE_TIME     TIMESTAMP NOT NULL,
    RELEASE_TIME    TIMESTAMP,
    REMARK          VARCHAR2(255 CHAR),
    CREATE_TIME     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATE_TIME     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CREATE_BY       VARCHAR2(50 CHAR),
    UPDATE_BY       VARCHAR2(50 CHAR),

    CONSTRAINT PK_SEAT_LOCK PRIMARY KEY (SEAT_LOCK_ID),
    CONSTRAINT FK_SEAT_LOCK_SEAT FOREIGN KEY (SEAT_ID) REFERENCES SEAT(SEAT_ID),
    --CONSTRAINT FK_SEAT_LOCK_SESSION FOREIGN KEY (SESSION_ID) REFERENCES SESSION(SESSION_ID),
    --CONSTRAINT FK_SEAT_LOCK_USER FOREIGN KEY (USER_ID) REFERENCES "USER"(USER_ID),
    CONSTRAINT UK_SEAT_LOCK_TOKEN UNIQUE (LOCK_TOKEN),
    CONSTRAINT CK_SEAT_LOCK_STATUS CHECK ( LOCK_STATUS IN ('ACTIVE', 'RELEASED', 'EXPIRED', 'CONVERTED')),
    CONSTRAINT CK_SEAT_LOCK_TIME CHECK (EXPIRE_TIME > LOCK_TIME),
    CONSTRAINT CK_SEAT_LOCK_RELEASE_TIME CHECK (RELEASE_TIME IS NULL OR RELEASE_TIME >= LOCK_TIME )
);

-- 同一场次、同一座位，只允许存在一条 ACTIVE 锁座记录
CREATE UNIQUE INDEX UK_SEAT_LOCK_ACTIVE ON SEAT_LOCK (CASE WHEN LOCK_STATUS = 'ACTIVE' THEN SESSION_ID END,CASE WHEN LOCK_STATUS = 'ACTIVE' THEN SEAT_ID END);

-- 5. 座位预订表
CREATE TABLE SEAT_RESERVATION (
    SEAT_RESERVATION_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    SESSION_ID          NUMBER(19) NOT NULL,
    SEAT_ID             NUMBER(19) NOT NULL,
    ORDER_ITEM_ID       NUMBER(19),
    SEAT_LOCK_ID        NUMBER(19),
    RESERVATION_TYPE    VARCHAR2(20 CHAR) DEFAULT 'ORDER' NOT NULL,
    RESERVATION_STATUS  VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    RESERVE_TIME        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CANCEL_TIME         TIMESTAMP,
    HOLD_REASON         VARCHAR2(255 CHAR),
    REMARK              VARCHAR2(255 CHAR),
    CREATE_TIME         TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATE_TIME         TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CREATE_BY           VARCHAR2(50 CHAR),
    UPDATE_BY           VARCHAR2(50 CHAR),

    CONSTRAINT PK_SEAT_RESERVATION PRIMARY KEY (SEAT_RESERVATION_ID),
    CONSTRAINT FK_SEAT_RESERVATION_SEAT FOREIGN KEY (SEAT_ID)REFERENCES SEAT(SEAT_ID),
    CONSTRAINT FK_SEAT_RESERVATION_LOCK FOREIGN KEY (SEAT_LOCK_ID)REFERENCES SEAT_LOCK(SEAT_LOCK_ID),
    --CONSTRAINT FK_SEAT_RESERVATION_SESSION FOREIGN KEY (SESSION_ID) REFERENCES SESSION(SESSION_ID),
    --CONSTRAINT FK_SEAT_RESERVATION_ORDER_ITEM FOREIGN KEY (ORDER_ITEM_ID) REFERENCES ORDER_ITEM(ORDER_ITEM_ID),

    -- 一条订单明细最多对应一条正式占座记录
    CONSTRAINT UK_SEAT_RESERVATION_ORDER_ITEM UNIQUE (ORDER_ITEM_ID),

    -- 一个锁座记录最多转成一条正式占座记录
    CONSTRAINT UK_SEAT_RESERVATION_LOCK UNIQUE (SEAT_LOCK_ID),

    CONSTRAINT CK_SEAT_RESERVATION_TYPE CHECK (RESERVATION_TYPE IN ('ORDER', 'SYSTEM', 'VIP')),
    CONSTRAINT CK_SEAT_RESERVATION_STATUS CHECK (RESERVATION_STATUS IN ('ACTIVE', 'CANCELLED', 'RELEASED')),
    CONSTRAINT CK_SEAT_RESERVATION_CANCEL CHECK (CANCEL_TIME IS NULL OR CANCEL_TIME >= RESERVE_TIME ),
    CONSTRAINT CK_SEAT_RESERVATION_ORDER_ITEM CHECK ((RESERVATION_TYPE = 'ORDER' AND ORDER_ITEM_ID IS NOT NULL) OR (RESERVATION_TYPE IN ('SYSTEM', 'VIP')AND ORDER_ITEM_ID IS NULL))
);

-- 同一场次、同一座位，只允许存在一条 ACTIVE 正式占座记录
CREATE UNIQUE INDEX UK_SEAT_RESERVATION_ACTIVE ON SEAT_RESERVATION (CASE WHEN RESERVATION_STATUS = 'ACTIVE' THEN SESSION_ID END,CASE WHEN RESERVATION_STATUS = 'ACTIVE' THEN SEAT_ID END);

-- 6. 选座规则表
CREATE TABLE SEAT_RULE (
    SEAT_RULE_ID            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    RULE_CODE               VARCHAR2(30 CHAR) NOT NULL,
    RULE_NAME               VARCHAR2(100 CHAR) NOT NULL,
    RULE_TYPE               VARCHAR2(30 CHAR) NOT NULL,
    MIN_SEAT_COUNT          NUMBER(3) DEFAULT 1 NOT NULL,
    MAX_SEAT_COUNT          NUMBER(3) DEFAULT 10 NOT NULL,
    ALLOW_CROSS_ROW         CHAR(1) DEFAULT 'N' NOT NULL,
    ALLOW_CROSS_SECTION     CHAR(1) DEFAULT 'N' NOT NULL,
    PRIORITY                NUMBER(5) DEFAULT 100 NOT NULL,
    RULE_STATUS             VARCHAR2(20 CHAR) DEFAULT 'ENABLED' NOT NULL,
    REMARK                  VARCHAR2(255 CHAR),
    CREATE_TIME             TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATE_TIME             TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CREATE_BY               VARCHAR2(50 CHAR),
    UPDATE_BY               VARCHAR2(50 CHAR),

    CONSTRAINT PK_SEAT_RULE PRIMARY KEY (SEAT_RULE_ID),
    CONSTRAINT UK_SEAT_RULE_CODE UNIQUE (RULE_CODE),
    CONSTRAINT CK_SEAT_RULE_TYPE CHECK ( RULE_TYPE IN ('CONTINUOUS', 'NO_SINGLE_LEFT', 'LIMIT_COUNT', 'SECTION_LIMIT')),
    CONSTRAINT CK_SEAT_RULE_CROSS_ROW CHECK (ALLOW_CROSS_ROW IN ('Y', 'N')),
    CONSTRAINT CK_SEAT_RULE_CROSS_SECTION CHECK (ALLOW_CROSS_SECTION IN ('Y', 'N')),
    CONSTRAINT CK_SEAT_RULE_STATUS CHECK (RULE_STATUS IN ('ENABLED', 'DISABLED')),
    CONSTRAINT CK_SEAT_RULE_COUNT CHECK (MIN_SEAT_COUNT <= MAX_SEAT_COUNT),
    CONSTRAINT CK_SEAT_RULE_PRIORITY CHECK (PRIORITY >= 0)
);

-- 7. 规则适用范围表
CREATE TABLE SEAT_RULE_SCOPE (
    RULE_SCOPE_ID  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    SEAT_RULE_ID        NUMBER(19) NOT NULL,
    SCOPE_TYPE          VARCHAR2(20 CHAR) NOT NULL,
    SEAT_MAP_ID         NUMBER(19),
    SEAT_SECTION_ID     NUMBER(19),
    SCOPE_STATUS        VARCHAR2(20 CHAR) DEFAULT 'ENABLED' NOT NULL,
    CREATE_TIME         TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATE_TIME         TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CREATE_BY           VARCHAR2(50 CHAR),
    UPDATE_BY           VARCHAR2(50 CHAR),

    CONSTRAINT PK_SEAT_RULE_SCOPE PRIMARY KEY (RULE_SCOPE_ID),
    CONSTRAINT FK_SEAT_RULE_SCOPE_RULE FOREIGN KEY (SEAT_RULE_ID) REFERENCES SEAT_RULE(SEAT_RULE_ID),
    CONSTRAINT FK_SEAT_RULE_SCOPE_MAP FOREIGN KEY (SEAT_MAP_ID) REFERENCES SEAT_MAP(SEAT_MAP_ID),
    CONSTRAINT FK_SEAT_RULE_SCOPE_SECTION FOREIGN KEY (SEAT_SECTION_ID) REFERENCES SEAT_SECTION(SEAT_SECTION_ID),
    CONSTRAINT CK_SEAT_RULE_SCOPE_TYPE CHECK (SCOPE_TYPE IN ('MAP', 'SECTION')),
    CONSTRAINT CK_SEAT_RULE_SCOPE_STATUS CHECK (SCOPE_STATUS IN ('ENABLED', 'DISABLED')),

    -- MAP 范围只能填 SEAT_MAP_ID；SECTION 范围只能填 SEAT_SECTION_ID
    CONSTRAINT CK_SEAT_RULE_SCOPE_TARGET CHECK ((SCOPE_TYPE = 'MAP' AND SEAT_MAP_ID IS NOT NULL AND SEAT_SECTION_ID IS NULL) OR (SCOPE_TYPE = 'SECTION' AND SEAT_SECTION_ID IS NOT NULL AND SEAT_MAP_ID IS NULL))
);

-- 同一规则不能重复配置到同一张座位图
CREATE UNIQUE INDEX UK_SEAT_RULE_SCOPE_MAP ON SEAT_RULE_SCOPE ( CASE WHEN SCOPE_TYPE = 'MAP' THEN SEAT_RULE_ID END,CASE WHEN SCOPE_TYPE = 'MAP' THEN SEAT_MAP_ID END);

-- 同一规则不能重复配置到同一个票区
CREATE UNIQUE INDEX UK_SEAT_RULE_SCOPE_SECTION ON SEAT_RULE_SCOPE ( CASE WHEN SCOPE_TYPE = 'SECTION' THEN SEAT_RULE_ID END, CASE WHEN SCOPE_TYPE = 'SECTION' THEN SEAT_SECTION_ID END);

