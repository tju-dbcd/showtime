    PAY_STATUS          VARCHAR2(20 CHAR)
        DEFAULT 'PENDING' NOT NULL,

    TRADE_NO            VARCHAR2(100 CHAR),

    CALLBACK_DATA       CLOB,

    CALLBACK_TIME       TIMESTAMP,

