        UNIQUE(PAYMENT_NO),

    CONSTRAINT CHK_PAYMENT_AMOUNT
        CHECK(PAY_AMOUNT>=0),

    CONSTRAINT CHK_PAYMENT_REFUND
        CHECK
        (
            REFUND_AMOUNT>=0
            AND
            REFUND_AMOUNT<=PAY_AMOUNT
        ),

    CONSTRAINT CHK_PAYMENT_CHANNEL
        CHECK
        (
            PAY_CHANNEL IN
            (
                'ALIPAY',
                'WECHAT',
                'UNIONPAY',
                'BALANCE'
            )
        ),

    CONSTRAINT CHK_PAYMENT_STATUS
        CHECK
        (
            PAY_STATUS IN
            (
                'PENDING',
                'SUCCESS',
                'FAIL',
                'CLOSED'
            )
        )
);

