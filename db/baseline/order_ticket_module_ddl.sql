CREATE TABLE T_ORDER
(
    ORDER_ID            NUMBER(19)
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_T_ORDER PRIMARY KEY,

    ORDER_NO            VARCHAR2(30 CHAR) NOT NULL,

    USER_ID             NUMBER(19) NOT NULL,

    SESSION_ID          NUMBER(19) NOT NULL,

    ORDER_TYPE          VARCHAR2(20 CHAR)
        DEFAULT 'NORMAL' NOT NULL,

    PARENT_ORDER_ID     NUMBER(19),

    TOTAL_AMOUNT        NUMBER(12,2)
        DEFAULT 0 NOT NULL,

    DISCOUNT_AMOUNT     NUMBER(12,2)
        DEFAULT 0 NOT NULL,

    ACTUAL_AMOUNT       NUMBER(12,2)
        DEFAULT 0 NOT NULL,

    TICKET_COUNT        NUMBER(5)
        DEFAULT 1 NOT NULL,

    ORDER_STATUS        VARCHAR2(20 CHAR)
        DEFAULT 'PENDING_PAY' NOT NULL,

    EXPIRE_TIME         TIMESTAMP
        DEFAULT CURRENT_TIMESTAMP NOT NULL,

    PAY_TIME            TIMESTAMP,

    ISSUE_TIME          TIMESTAMP,

    CANCEL_TIME         TIMESTAMP,

    SOURCE              VARCHAR2(20 CHAR)
        DEFAULT 'WEB' NOT NULL,

    IP_ADDRESS          VARCHAR2(50 CHAR),

    REMARK              VARCHAR2(500 CHAR),

    CREATE_TIME         TIMESTAMP
        DEFAULT CURRENT_TIMESTAMP NOT NULL,

    UPDATE_TIME         TIMESTAMP
        DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CREATE_BY           VARCHAR2(50 CHAR),

    UPDATE_BY           VARCHAR2(50 CHAR),

    CONSTRAINT UK_T_ORDER_NO
        UNIQUE(ORDER_NO),

    CONSTRAINT CHK_T_ORDER_TYPE
        CHECK
        (
            ORDER_TYPE IN
            (
                'NORMAL',
                'SPLIT',
                'MERGE',
                'EXCHANGE'
            )
        ),

    CONSTRAINT CHK_T_ORDER_STATUS
        CHECK
        (
            ORDER_STATUS IN
            (
                'PENDING_PAY',
                'PAID',
                'ISSUED',
                'PART_REFUND',
                'REFUNDED',
                'CANCELLED'
            )
        ),

    CONSTRAINT CHK_T_ORDER_TOTAL
        CHECK(TOTAL_AMOUNT>=0),

    CONSTRAINT CHK_T_ORDER_DISCOUNT
        CHECK(DISCOUNT_AMOUNT>=0),

    CONSTRAINT CHK_T_ORDER_ACTUAL
        CHECK(ACTUAL_AMOUNT>=0),

    CONSTRAINT CHK_T_ORDER_COUNT
        CHECK(TICKET_COUNT>0)
);

ALTER TABLE T_ORDER
